import "dotenv/config";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { setupEvalEnv } from "./harness.js";
import { hasLlmProvider } from "./llmHelper.js";
import type { Scenario, Category } from "./types.js";
import { toolSelectionScenarios } from "./scenarios/toolSelection.js";
import { retrievalAccuracyScenarios } from "./scenarios/retrievalAccuracy.js";
import { invalidInputScenarios } from "./scenarios/invalidInput.js";
import { missingDataScenarios } from "./scenarios/missingData.js";
import { authorizationScenarios } from "./scenarios/authorization.js";
import { incorrectAssumptionsScenarios } from "./scenarios/incorrectAssumptions.js";
import { multiStepWorkflowScenarios } from "./scenarios/multiStepWorkflows.js";

const __dirname = dirname(fileURLToPath(import.meta.url));

const ALL_SCENARIOS: Scenario[] = [
  ...toolSelectionScenarios,
  ...retrievalAccuracyScenarios,
  ...invalidInputScenarios,
  ...missingDataScenarios,
  ...authorizationScenarios,
  ...incorrectAssumptionsScenarios,
  ...multiStepWorkflowScenarios,
];

interface ScenarioResult {
  id: string;
  category: Category;
  description: string;
  status: "pass" | "fail" | "skipped";
  message?: string;
  durationMs: number;
}

async function runScenario(scenario: Scenario): Promise<ScenarioResult> {
  const start = Date.now();

  if (scenario.requiresLlm && !hasLlmProvider()) {
    return { id: scenario.id, category: scenario.category, description: scenario.description, status: "skipped", message: "no LLM provider configured (ANTHROPIC_API_KEY or NIM_API_KEY)", durationMs: 0 };
  }

  try {
    const env = await setupEvalEnv();
    await scenario.run(env);
    return { id: scenario.id, category: scenario.category, description: scenario.description, status: "pass", durationMs: Date.now() - start };
  } catch (err) {
    return {
      id: scenario.id,
      category: scenario.category,
      description: scenario.description,
      status: "fail",
      message: err instanceof Error ? err.message : String(err),
      durationMs: Date.now() - start,
    };
  }
}

function summarizeByCategory(results: ScenarioResult[]) {
  const categories = [...new Set(results.map((r) => r.category))];
  return categories.map((category) => {
    const inCategory = results.filter((r) => r.category === category);
    return {
      category,
      total: inCategory.length,
      passed: inCategory.filter((r) => r.status === "pass").length,
      failed: inCategory.filter((r) => r.status === "fail").length,
      skipped: inCategory.filter((r) => r.status === "skipped").length,
    };
  });
}

function renderMarkdown(results: ScenarioResult[], summary: ReturnType<typeof summarizeByCategory>): string {
  const total = results.length;
  const passed = results.filter((r) => r.status === "pass").length;
  const failed = results.filter((r) => r.status === "fail").length;
  const skipped = results.filter((r) => r.status === "skipped").length;
  const passRateOfRun = total - skipped > 0 ? Math.round((passed / (total - skipped)) * 1000) / 10 : 0;

  const lines: string[] = [];
  lines.push("# StudyGraph MCP — Agent Evaluations");
  lines.push("");
  lines.push(`Generated by \`npm run eval\` on ${new Date().toISOString()}.`);
  lines.push("");
  lines.push(
    "This suite runs 34 scenarios against the MCP server's 8 tools: correct tool selection, " +
      "accurate retrieval, invalid input handling, missing data, authorization failures, incorrect " +
      "assumptions, and multi-step workflows. Most scenarios call tools directly against an in-memory, " +
      "freshly seeded copy of the demo dataset (`mode: direct-call`); the 6 tool-selection scenarios " +
      "drive a real LLM tool-use turn (`mode: llm-driven`, via Anthropic or NVIDIA NIM) and are " +
      "skipped, not failed, when neither `ANTHROPIC_API_KEY` nor `NIM_API_KEY` is set."
  );
  lines.push("");
  lines.push(`**Result: ${passed}/${total - skipped} passed` + (skipped > 0 ? `, ${skipped} skipped` : "") + ` (${passRateOfRun}% pass rate of scenarios actually run).**`);
  lines.push("");
  lines.push("## Summary by category");
  lines.push("");
  lines.push("| Category | Total | Passed | Failed | Skipped |");
  lines.push("|---|---|---|---|---|");
  for (const s of summary) {
    lines.push(`| ${s.category} | ${s.total} | ${s.passed} | ${s.failed} | ${s.skipped} |`);
  }
  lines.push("");
  lines.push("## Full results");
  lines.push("");
  lines.push("| ID | Category | Description | Status | Notes |");
  lines.push("|---|---|---|---|---|");
  for (const r of results) {
    const icon = r.status === "pass" ? "✅" : r.status === "fail" ? "❌" : "⏭️";
    lines.push(`| ${r.id} | ${r.category} | ${r.description} | ${icon} ${r.status} | ${r.message ? r.message.replace(/\|/g, "\\|") : ""} |`);
  }
  lines.push("");
  return lines.join("\n");
}

async function main() {
  console.log(`Running ${ALL_SCENARIOS.length} eval scenarios...\n`);
  if (!hasLlmProvider()) {
    console.log("No LLM provider configured (set ANTHROPIC_API_KEY or NIM_API_KEY) -- the 6 tool-selection (llm-driven) scenarios will be skipped.\n");
  }

  const results: ScenarioResult[] = [];
  for (const scenario of ALL_SCENARIOS) {
    const result = await runScenario(scenario);
    results.push(result);
    const icon = result.status === "pass" ? "PASS" : result.status === "fail" ? "FAIL" : "SKIP";
    console.log(`[${icon}] ${result.id} -- ${result.description}${result.message ? `\n       ${result.message}` : ""}`);
  }

  const summary = summarizeByCategory(results);
  const passed = results.filter((r) => r.status === "pass").length;
  const failed = results.filter((r) => r.status === "fail").length;
  const skipped = results.filter((r) => r.status === "skipped").length;

  console.log(`\n${passed} passed, ${failed} failed, ${skipped} skipped (of ${results.length} total scenarios).`);

  const resultsDir = join(__dirname, "results");
  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, "latest.json"), JSON.stringify({ generatedAt: new Date().toISOString(), summary, results }, null, 2));

  const docsPath = join(__dirname, "..", "docs", "EVALUATIONS.md");
  writeFileSync(docsPath, renderMarkdown(results, summary));
  console.log(`\nWrote evals/results/latest.json and docs/EVALUATIONS.md`);

  if (failed > 0) process.exitCode = 1;
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
